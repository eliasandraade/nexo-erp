using Nexo.Domain.Common;
using Nexo.Domain.Exceptions;

namespace Nexo.Domain.Modules.TaxIntelligence;

/// <summary>
/// One change of the module's runtime state (platform-wide, append-only): the platform activates the mode the
/// installation configured, suspends everything at once, or turns it back to inactive. The newest record is the
/// state in force. It never replaces the configuration: new work runs only when the configuration allows it and
/// the newest record is an activation of that same mode. Who and when come from the authenticated request.
/// </summary>
public class TaxModuleActivation : BaseEntity
{
    private TaxModuleActivation() { }   // EF Core

    public TaxModuleStatus Status { get; private set; }
    public TaxApprovalMode Mode { get; private set; }
    /// <summary>Where the decision behind the change is recorded.</summary>
    public string DecisionReference { get; private set; } = string.Empty;
    public string Reason { get; private set; } = string.Empty;
    public Guid ActorId { get; private set; }
    public string ActorName { get; private set; } = string.Empty;
    public string ActorRole { get; private set; } = string.Empty;

    public static TaxModuleActivation Activate(TaxApprovalMode mode, string decisionReference, string reason, Guid actorId, string actorName, string actorRole)
    {
        if (mode == TaxApprovalMode.Disabled)
            throw new DomainException("Escolha o modo a ativar: piloto controlado ou definitivo.", "tax_module_mode");
        if (string.IsNullOrWhiteSpace(decisionReference))
            throw new DomainException("Diga onde está registrada a decisão de ativar o módulo.", "tax_module_decision");
        return Build(TaxModuleStatus.Active, mode, decisionReference, reason, actorId, actorName, actorRole);
    }

    /// <summary>Stops every new run at once (incident, suspension criterion). Reading and verifying stay available.</summary>
    public static TaxModuleActivation Suspend(TaxApprovalMode mode, string reason, Guid actorId, string actorName, string actorRole)
        => Build(TaxModuleStatus.Suspended, mode, null, reason, actorId, actorName, actorRole);

    /// <summary>Back to inactive (end of the pilot, planned stop).</summary>
    public static TaxModuleActivation Deactivate(TaxApprovalMode mode, string reason, Guid actorId, string actorName, string actorRole)
        => Build(TaxModuleStatus.Inactive, mode, null, reason, actorId, actorName, actorRole);

    private static TaxModuleActivation Build(TaxModuleStatus status, TaxApprovalMode mode, string? decisionReference, string reason,
        Guid actorId, string actorName, string actorRole)
    {
        if (string.IsNullOrWhiteSpace(reason)) throw new DomainException("Informe o motivo da mudança de estado do módulo.", "tax_module_reason");
        if (actorId == Guid.Empty || string.IsNullOrWhiteSpace(actorName))
            throw new DomainException("A mudança de estado do módulo identifica quem a fez.", "tax_module_actor");
        return new TaxModuleActivation
        {
            Status = status,
            Mode = mode,
            DecisionReference = decisionReference?.Trim() ?? string.Empty,
            Reason = reason.Trim(),
            ActorId = actorId,
            ActorName = actorName.Trim(),
            ActorRole = string.IsNullOrWhiteSpace(actorRole) ? "desconhecido" : actorRole.Trim(),
        };
    }
}

/// <summary>
/// One professional review of a rule version, as received — append-only, so a later review never erases an
/// earlier one. The professional identity (name, registration) is what was informed; who recorded it in the
/// system and when are the authenticated user and the server clock, kept apart. Nothing here is generated by
/// the system: a review exists only when someone records one that really happened.
/// </summary>
public class TaxProfessionalReviewRecord : BaseEntity
{
    private TaxProfessionalReviewRecord() { }   // EF Core

    public Guid RuleVersionId { get; private set; }
    public ProfessionalReviewStatus Status { get; private set; }
    public ProfessionalReviewStatus PreviousStatus { get; private set; }
    /// <summary>The professional, as informed (never the user who recorded it).</summary>
    public string Reviewer { get; private set; } = string.Empty;
    /// <summary>Professional identification as informed (e.g. a council registration), when the profession has one.</summary>
    public string? ProfessionalReference { get; private set; }
    /// <summary>Date of the review or opinion, as informed.</summary>
    public DateOnly? ReviewedOn { get; private set; }
    public string? Scope { get; private set; }
    /// <summary>Establishment regimes the review covers (names of <c>TaxRegime</c>). An approval holds only for them.</summary>
    public List<string> CoveredRegimes { get; private set; } = [];
    public DateOnly? ValidFrom { get; private set; }
    public DateOnly? ValidTo { get; private set; }
    public string? Assumptions { get; private set; }
    public string? Caveats { get; private set; }
    public string? Notes { get; private set; }
    /// <summary>The opinion or technical note, stored privately (<see cref="TaxPlatformDocument"/>).</summary>
    public Guid? SupportingDocumentId { get; private set; }
    public Guid RecordedById { get; private set; }
    public string RecordedByName { get; private set; } = string.Empty;
    public string RecordedByRole { get; private set; } = string.Empty;

    internal static TaxProfessionalReviewRecord From(Guid ruleVersionId, ProfessionalReviewStatus previous, ProfessionalReviewInput r)
        => new()
        {
            RuleVersionId = ruleVersionId,
            Status = r.Status,
            PreviousStatus = previous,
            Reviewer = r.Reviewer.Trim(),
            ProfessionalReference = Clean(r.ProfessionalReference),
            ReviewedOn = r.ReviewedOn,
            Scope = Clean(r.Scope),
            CoveredRegimes = r.CoveredRegimes.Select(x => x.Trim()).Where(x => x.Length > 0).Distinct().Order(StringComparer.Ordinal).ToList(),
            ValidFrom = r.ValidFrom,
            ValidTo = r.ValidTo,
            Assumptions = Clean(r.Assumptions),
            Caveats = Clean(r.Caveats),
            Notes = Clean(r.Notes),
            SupportingDocumentId = r.SupportingDocumentId,
            RecordedById = r.RecordedById,
            RecordedByName = r.RecordedByName.Trim(),
            RecordedByRole = r.RecordedByRole.Trim(),
        };

    private static string? Clean(string? s) => string.IsNullOrWhiteSpace(s) ? null : s.Trim();
}

/// <summary>
/// The materiality threshold of a company, versioned: from a date on, an estimated impact at or above it needs an
/// independent approver whatever the risk. Append-only — a new version never rewrites one already used, and a
/// decision records the version in force on its date. No threshold configured = no materiality rule (the default).
/// </summary>
public class TaxMaterialityPolicy : TenantEntity
{
    private TaxMaterialityPolicy() { }   // EF Core
    private TaxMaterialityPolicy(Guid tenantId) : base(tenantId) { }

    public int Version { get; private set; }
    public decimal Threshold { get; private set; }
    public string Currency { get; private set; } = "BRL";
    public DateOnly EffectiveFrom { get; private set; }
    public DateOnly? EffectiveTo { get; private set; }
    public string Rationale { get; private set; } = string.Empty;
    public string DecisionReference { get; private set; } = string.Empty;
    public Guid ConfiguredById { get; private set; }
    public string ConfiguredByName { get; private set; } = string.Empty;

    public const string SupportedCurrency = "BRL";

    public static TaxMaterialityPolicy Create(Guid tenantId, int version, decimal threshold, string currency, DateOnly effectiveFrom,
        DateOnly? effectiveTo, string rationale, string decisionReference, Guid byId, string byName)
    {
        if (threshold <= 0 || decimal.Round(threshold, 2) != threshold)
            throw new DomainException("A materialidade é um valor positivo em centavos.", "tax_materiality_threshold");
        if (!string.Equals(currency?.Trim(), SupportedCurrency, StringComparison.OrdinalIgnoreCase))
            throw new DomainException("A materialidade é informada em reais (BRL).", "tax_materiality_currency");
        if (effectiveTo is not null && effectiveTo < effectiveFrom)
            throw new DomainException("O fim da vigência é anterior ao início.", "tax_materiality_validity");
        if (string.IsNullOrWhiteSpace(rationale) || string.IsNullOrWhiteSpace(decisionReference))
            throw new DomainException("Diga por que este valor e onde a decisão está registrada.", "tax_materiality_decision");
        return new TaxMaterialityPolicy(tenantId)
        {
            Version = version,
            Threshold = threshold,
            Currency = SupportedCurrency,
            EffectiveFrom = effectiveFrom,
            EffectiveTo = effectiveTo,
            Rationale = rationale.Trim(),
            DecisionReference = decisionReference.Trim(),
            ConfiguredById = byId,
            ConfiguredByName = byName.Trim(),
        };
    }

    public bool Covers(DateOnly date) => EffectiveFrom <= date && (EffectiveTo is null || date <= EffectiveTo);

    /// <summary>The version in force on a date: the newest version whose validity covers it, or none.</summary>
    public static TaxMaterialityPolicy? InForce(IEnumerable<TaxMaterialityPolicy> versions, DateOnly date)
        => versions.Where(v => v.Covers(date)).OrderByDescending(v => v.Version).FirstOrDefault();
}

/// <summary>
/// How long a kind of tax evidence is kept — a policy, never a legal deadline invented by the software. A
/// platform default (no tenant) may be overridden by a company when the default allows it. No policy, or a
/// disabled one, means "keep": the engine only previews what a valid policy would make eligible; nothing is ever
/// discarded automatically, and a legal hold always wins. Append-only: a change is a new version.
/// </summary>
public class TaxRetentionPolicy : BaseEntity
{
    private TaxRetentionPolicy() { }   // EF Core

    /// <summary>Null = the platform default.</summary>
    public Guid? TenantId { get; private set; }
    public int Version { get; private set; }
    /// <summary>Evidence type it applies to; null = every type without a policy of its own.</summary>
    public TaxEvidenceType? EvidenceType { get; private set; }
    public int RetentionMonths { get; private set; }
    public TaxRetentionStart StartsAt { get; private set; }
    public bool Enabled { get; private set; }
    /// <summary>Platform default only: whether a company may set its own period for this type.</summary>
    public bool AllowTenantOverride { get; private set; }
    public string Rationale { get; private set; } = string.Empty;
    /// <summary>Where the rule or decision behind the period is documented.</summary>
    public string Reference { get; private set; } = string.Empty;
    public Guid ConfiguredById { get; private set; }
    public string ConfiguredByName { get; private set; } = string.Empty;
    public DateTime? SupersededAt { get; private set; }

    public bool IsCurrent => SupersededAt is null;

    public static TaxRetentionPolicy Create(Guid? tenantId, int version, TaxEvidenceType? evidenceType, int retentionMonths,
        TaxRetentionStart startsAt, bool enabled, bool allowTenantOverride, string rationale, string reference, Guid byId, string byName)
    {
        if (retentionMonths is < 1 or > 1200)
            throw new DomainException("O prazo de retenção vai de 1 a 1.200 meses.", "tax_retention_period");
        if (string.IsNullOrWhiteSpace(rationale) || string.IsNullOrWhiteSpace(reference))
            throw new DomainException("Diga por que este prazo e onde a regra ou decisão está documentada.", "tax_retention_reference");
        if (tenantId is not null && allowTenantOverride)
            throw new DomainException("Só a política padrão da plataforma define se a empresa pode sobrepor.", "tax_retention_override");
        return new TaxRetentionPolicy
        {
            TenantId = tenantId,
            Version = version,
            EvidenceType = evidenceType,
            RetentionMonths = retentionMonths,
            StartsAt = startsAt,
            Enabled = enabled,
            AllowTenantOverride = allowTenantOverride,
            Rationale = rationale.Trim(),
            Reference = reference.Trim(),
            ConfiguredById = byId,
            ConfiguredByName = byName.Trim(),
        };
    }

    public void Supersede(DateTime atUtc)
    {
        SupersededAt = atUtc;
        SetUpdatedAt();
    }

    /// <summary>The first day a file uploaded on <paramref name="uploadedOn"/> would stop being retained under this policy.</summary>
    public DateOnly EligibleFrom(DateOnly uploadedOn)
    {
        var start = StartsAt == TaxRetentionStart.EndOfUploadYear ? new DateOnly(uploadedOn.Year, 12, 31) : uploadedOn;
        return start.AddMonths(RetentionMonths).AddDays(1);
    }
}
